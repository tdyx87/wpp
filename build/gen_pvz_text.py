#!/usr/bin/env python3
# ===========================================================================
#  gen_pvz_text.py -- regenerate games/pvz/pvz_text.h
# ---------------------------------------------------------------------------
#  pvz_text.h must be GBK (code page 936) because WFont rasterises GB2312 and
#  the file is read with the system ANSI code page.  Writing it from the editor
#  would produce UTF-8 and the labels would come out as mojibake, so the table
#  is generated from this one ordered list instead: the enum and the string
#  array are emitted from the same pass, which makes it impossible for them to
#  drift out of order (the warfire tag table taught us that lesson).
#
#  Run from the repository root:  python build/gen_pvz_text.py
# ===========================================================================
import os

# (enum suffix, GBK text)
ENTRIES = [
    ("TITLE",   "草坪保卫战"),
    ("SUBTITLE","卡通风格原型"),
    ("PRESS",   "按 回车 进入"),
    ("HOWTO",   "操作说明"),
    ("START",   "开始游戏"),
    ("BACK",    "返回"),
    ("QUIT",    "退出"),
    ("SUN",     "阳光"),
    ("LEFT",    "剩余僵尸"),
    ("WIN",     "胜利！草坪守住了"),
    ("LOSE",    "失败  僵尸吃光了脑子"),
    ("RESTART", "R 重来    Esc 返回"),
    ("PEASH",   "豌豆射手"),
    ("SUNFL",   "向日葵"),
    ("WALLN",   "坚果墙"),
    ("SNOWP",   "寒冰射手"),
    ("CHERRY",  "樱桃炸弹"),
    ("ZOMB",    "普通僵尸"),
    ("SEEDBAR", "种子包"),
    ("LAWN",    "草坪"),
    ("TIP1",    "点种子包选中，再点草坪空位种下植物"),
    ("TIP2",    "阳光每 2 秒自动 +25，向日葵也会产出阳光"),
    ("TIP3",    "把豌豆射手种在僵尸那一行，别让僵尸走到最左边的房子"),
    ("KILL",    "击杀"),
    ("SELECT",  "当前选中"),
    ("WAVE",    "第 %d/10 波"),
    ("BIGWAVE", "大波僵尸来袭"),
    ("CONE",    "路障僵尸"),
    ("BUCKET",  "铁桶僵尸"),
    ("SUNDROP", "点击收集阳光"),
]

HEAD = """/* ===========================================================================
 *  pvz_text.h -- Lawn Defense : GBK label table
 * ---------------------------------------------------------------------------
 *  GENERATED by build/gen_pvz_text.py -- do not hand-edit.
 *
 *  This file is GBK (code page 936), NOT UTF-8, and it is the only source in
 *  games/pvz that is.  WFont rasterises GB2312 and the compiler reads the file
 *  with the system ANSI code page, so GBK is what both want.  The enum and the
 *  string array are emitted from one list so they cannot drift.
 * ===========================================================================
 */
#ifndef PVZ_TEXT_H
#define PVZ_TEXT_H

namespace pvz {

enum PvzLabel {
"""


def main():
    out = [HEAD]
    for i, (name, _) in enumerate(ENTRIES):
        out.append("    PVZ_LBL_%-10s = %d,\n" % (name, i))
    out.append("    PVZ_LABEL_COUNT\n};\n\n")
    out.append("static const char *const PVZ_LABEL[PVZ_LABEL_COUNT] = {\n")
    for name, text in ENTRIES:
        out.append('    "%s",%s/* PVZ_LBL_%s */\n'
                   % (text, " " * max(1, 26 - len(text) * 2), name))
    out.append("};\n\n} /* namespace pvz */\n\n#endif /* PVZ_TEXT_H */\n")

    blob = "".join(out).encode("gbk")

    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, "games", "pvz", "pvz_text.h")
    with open(path, "wb") as f:
        f.write(blob)

    # Sanity: every label must survive the encode/decode round trip and the
    # file must contain no UTF-8 BOM or replacement characters.
    assert b"\xef\xbb\xbf" not in blob
    assert b"\xef\xbf\xbd" not in blob
    for _, text in ENTRIES:
        assert text.encode("gbk") in blob, text
    print("wrote %s (%d bytes, %d labels)" % (path, len(blob), len(ENTRIES)))


if __name__ == "__main__":
    main()
