#!/usr/bin/env python3
# ===========================================================================
#  gen_gf_text.py -- regenerate games/guofeng/gf_text.h
# ---------------------------------------------------------------------------
#  gf_text.h must be GBK (code page 936) because WFont rasterises GB2312 and
#  the file is read with the system ANSI code page.  Writing it from the
#  editor would produce UTF-8 and the labels would come out as mojibake, so
#  the table is generated from this one ordered list instead: the enum and the
#  string array are emitted from the same pass, which makes it impossible for
#  them to drift out of order.
#
#  Run from the repository root:  python build/gen_gf_text.py
# ===========================================================================
import os

# (enum suffix, GBK text)
ENTRIES = [
    ("TITLE",    "云隐村"),
    ("SUBTITLE", "国风等距原型"),
    ("PRESS",    "按 回车 进入"),
    ("HOWTO",    "操作说明"),
    ("MOVE",     "移动"),
    ("RUN",      "奔跑"),
    ("MAP",      "地图"),
    ("BACK",     "返回"),
    ("QUIT",     "退出"),
    ("POS",      "位置"),
    ("FPS",      "帧率"),
    ("DRAWS",    "绘制"),
    ("TILES",    "瓦片"),
    ("LEGEND",   "图例"),
    ("ISO",      "等距投影"),
    ("DEPTH",    "深度排序"),
    ("LIGHT",    "加色光效"),
    ("BLEND",    "瓦片过渡"),
    ("UI",       "界面"),
    ("PLAQUE",   "匾额"),
    ("CLOSE",    "关闭"),
    ("HINT",     "W A S D 移动   Shift 奔跑   M 地图   Esc 退出"),
    ("BAMBOO",   "竹"),
    ("PINE",     "松"),
    ("ROCK",     "石"),
    ("LANTERN",  "灯"),
    ("HOUSE",    "屋"),
    ("WELL",     "井"),
    ("WATER",    "水"),
    ("GRASS",    "草"),
    ("PATH",     "径"),
    ("PAVE",     "砖"),
    ("STONE",    "岩"),
    ("HERO",     "主角"),
    ("CAMERA",   "镜头"),
    ("VILLAGE",  "村落"),
    ("POND",     "池塘"),
    ("WALK",     "行走"),
    ("SEAL",     "云"),
    ("BRIDGE",   "桥"),
]

HEAD = """/* ===========================================================================
 *  gf_text.h -- Guofeng : GBK label table
 * ---------------------------------------------------------------------------
 *  GENERATED by build/gen_gf_text.py -- do not hand-edit.
 *
 *  This file is GBK (code page 936), NOT UTF-8, and it is the only source in
 *  games/guofeng that is.  WFont rasterises GB2312 and the compiler reads the
 *  file with the system ANSI code page, so GBK is what both want.  The enum
 *  and the string array are emitted from one list so they cannot drift.
 * ===========================================================================
 */
#ifndef GF_TEXT_H
#define GF_TEXT_H

namespace gf {

enum GfLabel {
"""


def main():
    out = [HEAD]
    for i, (name, _) in enumerate(ENTRIES):
        out.append("    GF_LBL_%-10s = %d,\n" % (name, i))
    out.append("    GF_LABEL_COUNT\n};\n\n")
    out.append("static const char *const GF_LABEL[GF_LABEL_COUNT] = {\n")
    for name, text in ENTRIES:
        out.append('    "%s",%s/* GF_LBL_%s */\n'
                   % (text, " " * max(1, 26 - len(text) * 2), name))
    out.append("};\n\n} /* namespace gf */\n\n#endif /* GF_TEXT_H */\n")

    blob = "".join(out).encode("gbk")

    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, "games", "guofeng", "gf_text.h")
    with open(path, "wb") as f:
        f.write(blob)

    # Sanity: every label must survive the encode/decode round trip and the
    # file must contain no UTF-8 BOM or replacement characters.
    assert b"\xef\xbb\xbf" not in blob
    assert b"\xef\xbf\xbd" not in blob
    for _, text in ENTRIES:
        assert text.encode("gbk") in blob, text
    print("wrote %s (%d bytes, %d labels)" % (path, len(blob), len(ENTRIES)))


if __name__ == "__main__":
    main()
